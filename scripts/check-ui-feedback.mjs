import assert from 'node:assert/strict';
import { gardenReducer as reduce, initialState } from '../src/game/garden.ts';
import { gardenUIReducer, initialGardenUI, NOTICE_DURATION, visibleNotice } from '../src/game/notices.ts';

let state = initialState();
assert.equal(state.noticeRevision, 0, 'Startup does not allocate a permanent message banner');
state = reduce(state, { type: 'buy', id: 'carrot' });
const firstPurchase = state;
state = reduce(state, { type: 'buy', id: 'carrot' });
assert.equal(state.message, firstPurchase.message);
assert.equal(state.noticeRevision, firstPurchase.noticeRevision + 1, 'Buying the same seed again starts a fresh notice');
const revision = state.noticeRevision;
state = reduce(state, { type: 'selectSeed', id: 'carrot' });
state = reduce(state, { type: 'mode', quick: true });
state = reduce(state, { type: 'restoreNames', characterName: 'George', gardenName: 'Clover Corner' });
assert.equal(state.noticeRevision, revision, 'Quiet actions and hydration do not replay an old message');
assert.strictEqual(reduce(state, { type: 'buy', id: 'sunflower' }), state, 'Rejected purchases do not trigger a success notice');
const notice = { id: revision, text: state.message, expiresAt: 1000 + NOTICE_DURATION };
assert.strictEqual(visibleNotice(notice, 1000), notice);
assert.strictEqual(visibleNotice(notice, notice.expiresAt - 1), notice);
assert.equal(visibleNotice(notice, notice.expiresAt), null, 'The banner disappears at 2.5 seconds');
assert.equal(visibleNotice(notice, 60000), null, 'Returning from background never resurrects an expired banner');
assert.equal(visibleNotice(null, 1000), null);
let ui = gardenUIReducer(initialGardenUI(), { type: 'perform', action: { type: 'buy', id: 'carrot' }, now: 0 });
const oldNotice = ui.notice;
ui = gardenUIReducer(ui, { type: 'perform', action: { type: 'buy', id: 'carrot' }, now: 2000 });
assert.equal(ui.notice.expiresAt, 4500, 'A second identical message receives its own 2.5-second window');
assert.strictEqual(gardenUIReducer(ui, { type: 'expireNotice', id: oldNotice.id }), ui, 'An old timer cannot dismiss a newer message');
ui = gardenUIReducer(ui, { type: 'expireNotice', id: ui.notice.id });
assert.equal(ui.notice, null);
ui = gardenUIReducer(ui, { type: 'perform', action: { type: 'selectSeed', id: 'carrot' }, now: 5000 });
assert.equal(ui.notice, null, 'Seed selection after expiry keeps the banner hidden');
state = reduce(state, { type: 'plant', now: 1000 });
const growing = state;
assert.strictEqual(reduce(state, { type: 'tick', now: 5000 }), growing, 'Clock updates do not extend the notice');
state = reduce(state, { type: 'tick', now: state.session.deadline });
assert.equal(state.noticeRevision, growing.noticeRevision + 1, 'Readiness reports once');
assert.strictEqual(reduce(state, { type: 'tick', now: 100000 }), state, 'Ready plants do not repeatedly emit notices');
const ready = state;
state = reduce(state, { type: 'harvest' });
assert.equal(state.xp, ready.xp + 60);
assert.equal(state.coins, ready.coins + 29);
assert.equal(state.noticeRevision, ready.noticeRevision + 1);
console.log('Feedback checks passed: repeated purchases, silent selection/hydration, exact expiry, background gaps, and preserved focus rewards.');
